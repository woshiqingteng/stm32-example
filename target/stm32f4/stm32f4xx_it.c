/**
 * @file    stm32f4xx_it.c
 * @brief   Weak default handlers for core exceptions and peripheral IRQs.
 *
 * Every handler is a weak alias to Default_Handler, so any of them (including SysTick,
 * SVC and PendSV) can be overridden by a strong definition in a driver or module.
 */

void Default_Handler(void)
{
    for (;;)
    {
    }
}

